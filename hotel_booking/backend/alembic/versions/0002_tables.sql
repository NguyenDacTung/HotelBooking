
CREATE TABLE danh_tinh_dang_nhap (
	id UUID NOT NULL, 
	tai_khoan_id UUID NOT NULL, 
	provider VARCHAR(20) NOT NULL, 
	provider_subject VARCHAR(255) NOT NULL, 
	ngay_tao TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (id), 
	CHECK (provider IN ('GOOGLE','FACEBOOK')), 
	FOREIGN KEY(tai_khoan_id) REFERENCES tai_khoan (id)
)

;

CREATE INDEX ix_danh_tinh_dang_nhap_tai_khoan_id ON danh_tinh_dang_nhap (tai_khoan_id);

CREATE UNIQUE INDEX uq_identity_subject ON danh_tinh_dang_nhap (provider, provider_subject);


CREATE TABLE thong_bao (
	id UUID NOT NULL, 
	tai_khoan_id UUID NOT NULL, 
	loai_su_kien VARCHAR(40) NOT NULL, 
	tieu_de VARCHAR(150) NOT NULL, 
	noi_dung TEXT NOT NULL, 
	ma_pdp UUID, 
	ngay_tao TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	ngay_doc TIMESTAMP WITH TIME ZONE, 
	event_key VARCHAR(255) NOT NULL, 
	PRIMARY KEY (id), 
	FOREIGN KEY(tai_khoan_id) REFERENCES tai_khoan (id), 
	FOREIGN KEY(ma_pdp) REFERENCES phieu_dat_phong (ma_pdp), 
	UNIQUE (event_key)
)

;

CREATE INDEX ix_thong_bao_ma_pdp ON thong_bao (ma_pdp);

CREATE INDEX ix_thong_bao_tai_khoan_id ON thong_bao (tai_khoan_id);


CREATE TABLE giao_dich_thanh_toan (
	id UUID NOT NULL, 
	ma_pdp UUID NOT NULL, 
	loai VARCHAR(10) NOT NULL, 
	so_tien NUMERIC(14, 0) NOT NULL, 
	phuong_thuc VARCHAR(20) NOT NULL, 
	thoi_diem_giao_dich TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	nguoi_ghi_nhan UUID NOT NULL, 
	ghi_chu TEXT, 
	ma_tham_chieu VARCHAR(150), 
	giao_dich_goc_id UUID, 
	request_id UUID NOT NULL, 
	ngay_tao TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (id), 
	CHECK (so_tien > 0), 
	CHECK (loai IN ('THU','HOAN')), 
	CHECK (phuong_thuc IN ('TIEN_MAT','CHUYEN_KHOAN')), 
	CHECK ((loai='THU' AND giao_dich_goc_id IS NULL) OR (loai='HOAN' AND giao_dich_goc_id IS NOT NULL)), 
	FOREIGN KEY(ma_pdp) REFERENCES phieu_dat_phong (ma_pdp), 
	FOREIGN KEY(nguoi_ghi_nhan) REFERENCES tai_khoan (id), 
	FOREIGN KEY(giao_dich_goc_id) REFERENCES giao_dich_thanh_toan (id), 
	UNIQUE (request_id)
)

;

CREATE INDEX ix_giao_dich_thanh_toan_giao_dich_goc_id ON giao_dich_thanh_toan (giao_dich_goc_id);

CREATE INDEX ix_giao_dich_thanh_toan_ma_pdp ON giao_dich_thanh_toan (ma_pdp);

CREATE INDEX ix_giao_dich_thanh_toan_nguoi_ghi_nhan ON giao_dich_thanh_toan (nguoi_ghi_nhan);


CREATE TABLE audit_log (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	entity VARCHAR(40) NOT NULL, 
	entity_id VARCHAR(100) NOT NULL, 
	action VARCHAR(40) NOT NULL, 
	actor_id UUID NOT NULL, 
	before JSONB, 
	after JSONB, 
	ly_do TEXT NOT NULL, 
	thoi_diem TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (id), 
	FOREIGN KEY(actor_id) REFERENCES tai_khoan (id)
)

;

CREATE INDEX ix_audit_log_actor_id ON audit_log (actor_id);

CREATE INDEX ix_audit_log_entity_id ON audit_log (entity_id);