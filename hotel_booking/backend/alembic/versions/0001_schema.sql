CREATE EXTENSION IF NOT EXISTS btree_gist;


CREATE TABLE chuc_vu (
	ma_cv BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	ten_chuc_vu VARCHAR(80) NOT NULL, 
	ma_quyen VARCHAR(20) NOT NULL, 
	dang_su_dung BOOLEAN DEFAULT true NOT NULL, 
	PRIMARY KEY (ma_cv), 
	CHECK (ma_quyen IN ('LE_TAN','QUAN_LY')), 
	UNIQUE (ma_quyen)
)

;


CREATE TABLE loai_phong (
	ma_lp BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	ten_loai VARCHAR(100) NOT NULL, 
	mo_ta TEXT, 
	gia_co_ban NUMERIC(12, 0) NOT NULL, 
	suc_chua SMALLINT NOT NULL, 
	dien_tich_m2 NUMERIC(6, 1), 
	so_giuong SMALLINT, 
	dang_kinh_doanh BOOLEAN DEFAULT true NOT NULL, 
	PRIMARY KEY (ma_lp), 
	CHECK (gia_co_ban >= 0), 
	CHECK (suc_chua > 0), 
	CHECK (dien_tich_m2 > 0), 
	CHECK (so_giuong > 0), 
	UNIQUE (ten_loai)
)

;


CREATE TABLE tai_khoan (
	id UUID NOT NULL, 
	email VARCHAR(254) NOT NULL, 
	mat_khau_bam TEXT NOT NULL, 
	loai_tai_khoan VARCHAR(20) NOT NULL, 
	dang_hoat_dong BOOLEAN DEFAULT true NOT NULL, 
	ngay_tao TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (id), 
	CHECK (email = lower(trim(email))), 
	CHECK (loai_tai_khoan IN ('KHACH_HANG','NHAN_VIEN')), 
	UNIQUE (email)
)

;


CREATE TABLE tien_nghi (
	ma_tn BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	ten_tien_nghi VARCHAR(100) NOT NULL, 
	bieu_tuong VARCHAR(80), 
	PRIMARY KEY (ma_tn), 
	UNIQUE (ten_tien_nghi)
)

;


CREATE TABLE anh_loai_phong (
	ma_anh BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	ma_lp BIGINT NOT NULL, 
	duong_dan TEXT NOT NULL, 
	la_anh_bia BOOLEAN DEFAULT false NOT NULL, 
	thu_tu SMALLINT DEFAULT '0' NOT NULL, 
	PRIMARY KEY (ma_anh), 
	CHECK (thu_tu >= 0), 
	FOREIGN KEY(ma_lp) REFERENCES loai_phong (ma_lp)
)

;

CREATE INDEX ix_anh_loai_phong_ma_lp ON anh_loai_phong (ma_lp);

CREATE UNIQUE INDEX uq_anh_bia ON anh_loai_phong (ma_lp) WHERE la_anh_bia;


CREATE TABLE khach_hang (
	id UUID NOT NULL, 
	ho_ten VARCHAR(120) NOT NULL, 
	so_dien_thoai VARCHAR(20), 
	ngay_tao TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (id), 
	FOREIGN KEY(id) REFERENCES tai_khoan (id)
)

;


CREATE TABLE loai_phong_tien_nghi (
	ma_lp BIGINT NOT NULL, 
	ma_tn BIGINT NOT NULL, 
	PRIMARY KEY (ma_lp, ma_tn), 
	FOREIGN KEY(ma_lp) REFERENCES loai_phong (ma_lp), 
	FOREIGN KEY(ma_tn) REFERENCES tien_nghi (ma_tn)
)

;

CREATE INDEX ix_loai_phong_tien_nghi_ma_tn ON loai_phong_tien_nghi (ma_tn);


CREATE TABLE nhan_vien (
	id UUID NOT NULL, 
	ho_ten VARCHAR(120) NOT NULL, 
	ma_cv BIGINT NOT NULL, 
	dang_hoat_dong BOOLEAN DEFAULT true NOT NULL, 
	ngay_tao TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (id), 
	FOREIGN KEY(id) REFERENCES tai_khoan (id), 
	FOREIGN KEY(ma_cv) REFERENCES chuc_vu (ma_cv)
)

;

CREATE INDEX ix_nhan_vien_ma_cv ON nhan_vien (ma_cv);


CREATE TABLE phong (
	ma_phong BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	so_phong VARCHAR(20) NOT NULL, 
	ma_lp BIGINT NOT NULL, 
	tang SMALLINT, 
	ghi_chu TEXT, 
	dang_kinh_doanh BOOLEAN DEFAULT true NOT NULL, 
	PRIMARY KEY (ma_phong), 
	UNIQUE (so_phong), 
	FOREIGN KEY(ma_lp) REFERENCES loai_phong (ma_lp)
)

;

CREATE INDEX ix_phong_ma_lp ON phong (ma_lp);


CREATE TABLE phieu_dat_phong (
	ma_pdp UUID NOT NULL, 
	ma_kh UUID NOT NULL, 
	ma_phong BIGINT NOT NULL, 
	ngay_nhan DATE NOT NULL, 
	ngay_tra DATE NOT NULL, 
	so_khach SMALLINT NOT NULL, 
	don_gia_moi_dem NUMERIC(12, 0) NOT NULL, 
	tong_tien NUMERIC(14, 0) NOT NULL, 
	trang_thai VARCHAR(20) DEFAULT 'CHO_XAC_NHAN' NOT NULL, 
	ten_lien_he VARCHAR(120) NOT NULL, 
	sdt_lien_he VARCHAR(20) NOT NULL, 
	ghi_chu TEXT, 
	nhan_vien_xu_ly UUID, 
	ly_do_tu_choi TEXT, 
	ngay_tao TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	ngay_cap_nhat TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	ngay_xu_ly TIMESTAMP WITH TIME ZONE, 
	PRIMARY KEY (ma_pdp), 
	CHECK (ngay_tra > ngay_nhan AND ngay_tra - ngay_nhan <= 30), 
	CHECK (so_khach > 0), 
	CHECK (don_gia_moi_dem >= 0), 
	CHECK (tong_tien >= 0 AND tong_tien = don_gia_moi_dem * (ngay_tra - ngay_nhan)), 
	CHECK (trang_thai IN ('CHO_XAC_NHAN','DA_XAC_NHAN','DA_HUY','DA_TU_CHOI')), 
	CHECK (trang_thai <> 'DA_TU_CHOI' OR length(trim(ly_do_tu_choi)) > 0 AND ly_do_tu_choi IS NOT NULL), 
	CONSTRAINT ex_phong_khong_trung EXCLUDE USING gist (ma_phong WITH =, daterange(ngay_nhan, ngay_tra, '[)') WITH &&) WHERE (trang_thai IN ('CHO_XAC_NHAN','DA_XAC_NHAN')), 
	FOREIGN KEY(ma_kh) REFERENCES khach_hang (id), 
	FOREIGN KEY(ma_phong) REFERENCES phong (ma_phong), 
	FOREIGN KEY(nhan_vien_xu_ly) REFERENCES nhan_vien (id)
)

;

CREATE INDEX ix_phieu_dat_phong_ma_kh ON phieu_dat_phong (ma_kh);

CREATE INDEX ix_phieu_dat_phong_ma_phong ON phieu_dat_phong (ma_phong);

CREATE INDEX ix_phieu_dat_phong_nhan_vien_xu_ly ON phieu_dat_phong (nhan_vien_xu_ly);

CREATE INDEX ix_phieu_khach_ngay ON phieu_dat_phong (ma_kh, ngay_tao);

CREATE INDEX ix_phieu_trang_thai_ngay ON phieu_dat_phong (trang_thai, ngay_tao);


CREATE TABLE phong_tam_ngung (
	ma_ngung BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	ma_phong BIGINT NOT NULL, 
	tu_ngay DATE NOT NULL, 
	den_ngay DATE NOT NULL, 
	ly_do TEXT NOT NULL, 
	dang_hieu_luc BOOLEAN DEFAULT true NOT NULL, 
	nguoi_tao UUID NOT NULL, 
	ngay_tao TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (ma_ngung), 
	CHECK (den_ngay > tu_ngay), 
	CHECK (length(trim(ly_do)) > 0), 
	CONSTRAINT ex_ngung_khong_trung EXCLUDE USING gist (ma_phong WITH =, daterange(tu_ngay, den_ngay, '[)') WITH &&) WHERE (dang_hieu_luc), 
	FOREIGN KEY(ma_phong) REFERENCES phong (ma_phong), 
	FOREIGN KEY(nguoi_tao) REFERENCES tai_khoan (id)
)

;

CREATE INDEX ix_phong_tam_ngung_ma_phong ON phong_tam_ngung (ma_phong);

CREATE INDEX ix_phong_tam_ngung_nguoi_tao ON phong_tam_ngung (nguoi_tao);


CREATE TABLE lich_su_dat_phong (
	ma_ls BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	ma_pdp UUID NOT NULL, 
	tu_trang_thai VARCHAR(20), 
	den_trang_thai VARCHAR(20) NOT NULL, 
	nguoi_thuc_hien UUID NOT NULL, 
	ly_do TEXT, 
	thoi_diem TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (ma_ls), 
	CHECK (tu_trang_thai IN ('CHO_XAC_NHAN','DA_XAC_NHAN','DA_HUY','DA_TU_CHOI')), 
	CHECK (den_trang_thai IN ('CHO_XAC_NHAN','DA_XAC_NHAN','DA_HUY','DA_TU_CHOI')), 
	CHECK (tu_trang_thai IS NOT NULL OR den_trang_thai = 'CHO_XAC_NHAN'), 
	FOREIGN KEY(ma_pdp) REFERENCES phieu_dat_phong (ma_pdp), 
	FOREIGN KEY(nguoi_thuc_hien) REFERENCES tai_khoan (id)
)

;

CREATE INDEX ix_lich_su_dat_phong_nguoi_thuc_hien ON lich_su_dat_phong (nguoi_thuc_hien);

CREATE INDEX ix_lich_su_phieu_ngay ON lich_su_dat_phong (ma_pdp, thoi_diem);


CREATE FUNCTION verify_account_profile() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE account_id uuid; kind varchar; customers integer; employees integer;
BEGIN
  IF TG_OP = 'DELETE' THEN account_id := OLD.id; ELSE account_id := NEW.id; END IF;
  SELECT loai_tai_khoan INTO kind FROM tai_khoan WHERE id = account_id;
  IF NOT FOUND THEN RETURN NULL; END IF;
  SELECT count(*) INTO customers FROM khach_hang WHERE id = account_id;
  SELECT count(*) INTO employees FROM nhan_vien WHERE id = account_id;
  IF NOT ((kind = 'KHACH_HANG' AND customers = 1 AND employees = 0)
       OR (kind = 'NHAN_VIEN' AND customers = 0 AND employees = 1)) THEN
    RAISE EXCEPTION 'Account must have exactly one matching profile' USING ERRCODE = '23514';
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.id IS DISTINCT FROM NEW.id THEN
    SELECT loai_tai_khoan INTO kind FROM tai_khoan WHERE id = OLD.id;
    IF FOUND THEN
      SELECT count(*) INTO customers FROM khach_hang WHERE id = OLD.id;
      SELECT count(*) INTO employees FROM nhan_vien WHERE id = OLD.id;
      IF NOT ((kind = 'KHACH_HANG' AND customers = 1 AND employees = 0)
           OR (kind = 'NHAN_VIEN' AND customers = 0 AND employees = 1)) THEN
        RAISE EXCEPTION 'Old account lost its matching profile' USING ERRCODE = '23514';
      END IF;
    END IF;
  END IF;
  RETURN NULL;
END $$;


CREATE CONSTRAINT TRIGGER ck_profile_tai_khoan
AFTER INSERT OR UPDATE OR DELETE ON tai_khoan
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION verify_account_profile();

CREATE CONSTRAINT TRIGGER ck_profile_khach_hang
AFTER INSERT OR UPDATE OR DELETE ON khach_hang
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION verify_account_profile();

CREATE CONSTRAINT TRIGGER ck_profile_nhan_vien
AFTER INSERT OR UPDATE OR DELETE ON nhan_vien
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION verify_account_profile();